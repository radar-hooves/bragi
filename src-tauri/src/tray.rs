//! System tray integration for background playback.
//!
//! Provides a menu bar / system tray icon with playback controls so users
//! can control music without the main window visible.

use std::sync::Mutex;

use tauri::{
    image::Image,
    menu::{MenuBuilder, MenuItem, MenuItemBuilder},
    tray::{MouseButton, MouseButtonState, TrayIconBuilder, TrayIconEvent},
    AppHandle, Manager,
};

use crate::audio::AudioCommand;
use crate::state::AppState;

/// Tray icon identifier used for `tray_by_id` lookups.
const TRAY_ID: &str = "bragi-tray";

/// Holds a reference to the track info menu item for dynamic text updates.
pub struct TrayTrackInfoItem(Mutex<MenuItem<tauri::Wry>>);

/// Menu item IDs for the tray context menu.
mod ids {
    pub const TRACK_INFO: &str = "track-info";
    pub const PLAY_PAUSE: &str = "play-pause";
    pub const NEXT: &str = "next";
    pub const PREVIOUS: &str = "previous";
    pub const SHOW_WINDOW: &str = "show-window";
    pub const QUIT: &str = "quit";
}

/// Set up the system tray icon with playback controls.
///
/// Creates a tray icon with a context menu containing playback controls
/// and a "Show Window" / "Quit" option. Clicking the tray icon toggles
/// the main window visibility.
pub fn setup_tray(app: &AppHandle) -> Result<(), Box<dyn std::error::Error>> {
    // Build menu items.
    let track_info = MenuItemBuilder::with_id(ids::TRACK_INFO, "Not Playing")
        .enabled(false)
        .build(app)?;

    let play_pause = MenuItemBuilder::with_id(ids::PLAY_PAUSE, "Play/Pause").build(app)?;
    let next = MenuItemBuilder::with_id(ids::NEXT, "Next").build(app)?;
    let previous = MenuItemBuilder::with_id(ids::PREVIOUS, "Previous").build(app)?;
    let show_window = MenuItemBuilder::with_id(ids::SHOW_WINDOW, "Show Window").build(app)?;
    let quit = MenuItemBuilder::with_id(ids::QUIT, "Quit").build(app)?;

    let separator1 = tauri::menu::PredefinedMenuItem::separator(app)?;
    let separator2 = tauri::menu::PredefinedMenuItem::separator(app)?;

    // Build the tray menu.
    let menu = MenuBuilder::new(app)
        .items(&[
            &track_info,
            &separator1,
            &play_pause,
            &previous,
            &next,
            &separator2,
            &show_window,
            &quit,
        ])
        .build()?;

    // Store track info item in managed state so we can update its text later.
    app.manage(TrayTrackInfoItem(Mutex::new(track_info.clone())));

    // Build the tray icon with a stable ID for later lookups.
    //
    // macOS: a monochrome TEMPLATE image — the rune silhouette in pure black
    // with alpha (icons/tray-44.png, @2x, generated by
    // scripts/generate-tray-icon.py). macOS tints it for light/dark menu bars
    // and the pressed state. The full-colour app icon must never be used as a
    // template: template mode keeps only the alpha channel, so its opaque tile
    // flattens to a solid square.
    //
    // Elsewhere: the full-colour app icon, NOT template — Linux panels and the
    // Windows tray do no template tinting, so a black silhouette would vanish
    // on dark panels.
    #[cfg(target_os = "macos")]
    let (icon, as_template) = (
        Image::from_bytes(include_bytes!("../icons/tray-44.png"))?,
        true,
    );
    #[cfg(not(target_os = "macos"))]
    let (icon, as_template) = (
        Image::from_bytes(include_bytes!("../icons/64x64.png"))?,
        false,
    );
    let _tray = TrayIconBuilder::with_id(TRAY_ID)
        .icon(icon)
        .icon_as_template(as_template)
        .menu(&menu)
        .tooltip("Bragi")
        .on_menu_event(move |app, event| {
            handle_menu_event(app, event.id().as_ref());
        })
        .on_tray_icon_event(|tray, event| {
            if let TrayIconEvent::Click {
                button: MouseButton::Left,
                button_state: MouseButtonState::Up,
                ..
            } = event
            {
                toggle_active_window_visibility(tray.app_handle());
            }
        })
        .build(app)?;

    tracing::info!("System tray initialised");
    Ok(())
}

/// Handle a tray menu item click.
fn handle_menu_event(app: &AppHandle, item_id: &str) {
    match item_id {
        ids::PLAY_PAUSE => send_audio_command(app, AudioCommand::TogglePlayPause),
        ids::NEXT => send_audio_command(app, AudioCommand::SkipNext),
        ids::PREVIOUS => send_audio_command(app, AudioCommand::SkipPrevious),
        ids::SHOW_WINDOW => crate::window::show_active(app),
        ids::QUIT => {
            tracing::info!("Quit requested from system tray");
            app.exit(0);
        }
        _ => {}
    }
}

/// Send an audio command via the AppState handle.
fn send_audio_command(app: &AppHandle, command: AudioCommand) {
    let state = app.state::<AppState>();
    let audio = state.audio.clone();
    // Use try_read to avoid blocking the tray event handler.
    // The guard must be dropped before `audio`, so bind explicitly.
    let guard = audio.try_read();
    if let Ok(ref g) = guard {
        if let Some(handle) = g.as_ref() {
            let _ = handle.send(command);
        }
    }
}

/// Toggle Bragi's window between visible and hidden. Operates on whichever
/// window currently represents the app (`window::active_label` — the
/// MiniPlayer when it is open, `main` otherwise), so this never reveals the
/// main window on top of an already-open MiniPlayer.
fn toggle_active_window_visibility(app: &AppHandle) {
    let label = crate::window::active_label(app);
    if let Some(window) = app.get_webview_window(label) {
        if window.is_visible().unwrap_or(false) {
            let _ = window.hide();
        } else {
            desktop_shell::window::show(app, label);
        }
    }
}

/// Update the tray tooltip and track info menu item.
///
/// Called from the audio event emitter whenever the playback state changes.
pub fn update_tray_track_info(
    app: &AppHandle,
    track_name: Option<&str>,
    artist: Option<&str>,
    is_playing: bool,
) {
    let label = match track_name {
        Some(name) => {
            let status = if is_playing { "\u{25B6}" } else { "\u{23F8}" };
            // Build "Artist - Track" display string, truncated for menus.
            let display = match artist {
                Some(a) => format!("{} - {}", a, name),
                None => name.to_string(),
            };
            // Truncate at a safe character boundary for multi-byte UTF-8.
            let truncated = if display.len() > 50 {
                let end = display
                    .char_indices()
                    .map(|(i, _)| i)
                    .take_while(|&i| i <= 47)
                    .last()
                    .unwrap_or(0);
                format!("{}...", &display[..end])
            } else {
                display
            };
            format!("{} {}", status, truncated)
        }
        None => "Not Playing".to_string(),
    };

    // Update the tooltip on the tray icon.
    if let Some(tray) = app.tray_by_id(TRAY_ID) {
        let _ = tray.set_tooltip(Some(&label));
    }

    // Update the track info menu item text via the managed reference.
    if let Some(item) = app.try_state::<TrayTrackInfoItem>() {
        if let Ok(mi) = item.0.lock() {
            let _ = mi.set_text(&label);
        }
    }
}
